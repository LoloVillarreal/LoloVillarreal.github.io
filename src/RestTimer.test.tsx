// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { RestTimer } from './RestTimer'
import { resetRest, selectRestSession, setRestPreset } from './lib/rest-clock'

afterEach(()=>{cleanup();resetRest();setRestPreset(90);selectRestSession(null);sessionStorage.clear();vi.useRealTimers()})
describe('descanso en la guía',()=>{
  it('permite pausa, continuación y reinicio sin contar el tiempo pausado',()=>{
    vi.useFakeTimers();render(<RestTimer seconds={65}/>)
    fireEvent.click(screen.getByRole('button',{name:'Empezar descanso'}))
    act(()=>vi.advanceTimersByTime(35000));expect(screen.getByRole('timer').textContent).toBe('0:30')
    fireEvent.click(screen.getByRole('button',{name:'Pausar descanso'}))
    act(()=>vi.advanceTimersByTime(60000));expect(screen.getByRole('timer').textContent).toBe('0:30')
    fireEvent.click(screen.getByRole('button',{name:'Continuar descanso'}))
    act(()=>vi.advanceTimersByTime(30000));expect(screen.getByRole('timer').textContent).toBe('0:00')
    expect(screen.getByText('Descanso terminado')).toBeTruthy()
    fireEvent.click(screen.getByRole('button',{name:'Reiniciar descanso'}));expect(screen.getByRole('timer').textContent).toBe('1:05')
  })
  it('recupera el tiempo real al reanudar una pestaña suspendida',()=>{
    vi.useFakeTimers();render(<RestTimer seconds={90}/>)
    fireEvent.click(screen.getByRole('button',{name:'Empezar descanso'}))
    act(()=>{vi.setSystemTime(Date.now()+120000);document.dispatchEvent(new Event('visibilitychange'))})
    expect(screen.getByRole('timer').textContent).toBe('0:00')
    expect(screen.getByText('Descanso terminado')).toBeTruthy()
  })
  it('mantiene la pausa al abrir otro ejercicio, y usa el nuevo intervalo al repetir',()=>{
    vi.useFakeTimers()
    const original=render(<RestTimer seconds={150}/>)
    fireEvent.click(screen.getByRole('button',{name:'Empezar descanso'}))
    act(()=>vi.advanceTimersByTime(10000))
    fireEvent.click(screen.getByRole('button',{name:'Pausar descanso'}))
    original.unmount()
    act(()=>vi.advanceTimersByTime(60000))
    render(<RestTimer seconds={60}/>)
    expect(screen.getByRole('timer').textContent).toBe('2:20')
    fireEvent.click(screen.getByRole('button',{name:'Continuar descanso'}))
    act(()=>vi.advanceTimersByTime(140000))
    fireEvent.click(screen.getByRole('button',{name:'Repetir descanso'}))
    expect(screen.getByRole('timer').textContent).toBe('1:00')
  })
  it('recupera el reloj de la pestaña y lo descarta al cambiar de cuenta',async()=>{
    vi.useFakeTimers()
    const user={id:'ficticia-A',last_sign_in_at:'2026-11-12T12:00:00.000Z'}
    selectRestSession(user)
    const original=render(<RestTimer seconds={90}/>)
    fireEvent.click(screen.getByRole('button',{name:'Empezar descanso'}))
    original.unmount()
    act(()=>vi.advanceTimersByTime(20000))
    vi.resetModules()
    const { selectRestSession:resume }=await import('./lib/rest-clock')
    const { RestTimer:Reloaded }=await import('./RestTimer')
    resume(user)
    render(<Reloaded seconds={90}/>)
    expect(screen.getByRole('timer').textContent).toBe('1:10')
    act(()=>resume({...user,id:'ficticia-B'}))
    expect(screen.getByRole('timer').textContent).toBe('1:30')
    expect(screen.getByRole('button',{name:'Empezar descanso'})).toBeTruthy()
    expect(sessionStorage.getItem('la-rest-clock:'+user.id)).toBeNull()
  })
  it('solo restaura la pausa de 15 minutos cuando la cuenta coincide, incluso con igual fecha de acceso',async()=>{
    vi.useFakeTimers()
    const user={id:'cuenta-ficticia-A',last_sign_in_at:'2026-11-12T11:00:00Z'}
    selectRestSession(user)
    const view=render(<RestTimer seconds={900}/>)
    fireEvent.click(screen.getByRole('button',{name:'Empezar descanso'}))
    act(()=>vi.advanceTimersByTime(15000))
    fireEvent.click(screen.getByRole('button',{name:'Pausar descanso'}))
    view.unmount()
    act(()=>vi.advanceTimersByTime(3600000))
    vi.resetModules()
    const {selectRestSession:otherSession}=await import('./lib/rest-clock')
    otherSession({...user,id:'cuenta-ficticia-B'})
    const {RestTimer:OtherTimer}=await import('./RestTimer')
    const other=render(<OtherTimer seconds={90}/>)
    expect(screen.getByRole('timer').textContent).toBe('1:30')
    expect(screen.getByRole('button',{name:'Empezar descanso'})).toBeTruthy()
    other.unmount()
    vi.resetModules()
    const {selectRestSession:resume}=await import('./lib/rest-clock')
    const {RestTimer:Reloaded}=await import('./RestTimer')
    resume(user)
    render(<Reloaded seconds={90}/>)
    expect(screen.getByRole('timer').textContent).toBe('14:45')
    fireEvent.click(screen.getByRole('button',{name:'Continuar descanso'}))
    act(()=>vi.advanceTimersByTime(3000))
    expect(screen.getByRole('timer').textContent).toBe('14:42')
    act(()=>resume(null))
    expect(sessionStorage.getItem('la-rest-clock:'+user.id)).toBeNull()
  })
})
